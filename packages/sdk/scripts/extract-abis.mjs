// Extracts the `abi` field of the Foundry build output for the rose EVM contracts and the Sablier
// Lockup interface into `src/chains/base/abis.ts` as `as const` arrays. Run from packages/sdk after
// `forge build` at the repository root: `node scripts/extract-abis.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const out = join(root, "contracts", "evm", "out");

const sources = [
  ["roseVaultAbi", "RoseVault.sol/RoseVault.json"],
  ["testUsdcAbi", "TestUSDC.sol/TestUSDC.json"],
  ["demoStreamFaucetAbi", "DemoStreamFaucet.sol/DemoStreamFaucet.json"],
  ["demoTokenAbi", "DemoToken.sol/DemoToken.json"],
  ["sablierLockupAbi", "ISablierLockup.sol/ISablierLockup.json"],
];

let text = `// Generated by \`node scripts/extract-abis.mjs\` from the Foundry output in contracts/evm/out
// (\`forge build\` at the repository root). Do not edit by hand; rerun the script after a contract change.

`;
for (const [name, file] of sources) {
  const { abi } = JSON.parse(readFileSync(join(out, file), "utf8"));
  text += `/** ABI of \`contracts/evm/out/${file}\`. */\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(root, "packages", "sdk", "src", "chains", "base", "abis.ts"), text);
