/**
 * Writes the guided demo's data file for one engine (spec 9, "Watch a full round"):
 *
 *   node scripts/demo-manifest.ts [--env deployments/<engine>.env]
 *
 * Reads `deployments/e2e/cindral.json`, `deployments/e2e/<engine>.seed.json` and
 * `deployments/e2e/<engine>.live.json` (written by `seed.ts` and `e2e-live.ts`), plus
 * `deployments/e2e/<engine>.solana.json` when `e2e-solana-stream.mjs` ran (the Solana token
 * payout and redeem, shown in the Exit on Solana's payout step), builds the
 * manifest with the web app's own builder (`apps/web/src/lib/demo/manifest.ts`, so the file is
 * validated by the same code that reads it), writes `apps/web/src/content/demo/<engine>.json`,
 * and regenerates `apps/web/src/content/demo/index.ts`, the registry of every engine that has a
 * manifest. The app shows the demo only for the engine it is configured with
 * (`NEXT_PUBLIC_ENGINE_ACCOUNT`), so seeding a new engine and running this script is all the
 * demo needs to follow it.
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { buildDemoManifest, type Journal, type SolanaJournal } from "../apps/web/src/lib/demo/manifest.ts";
import { DEFAULT_ENV_FILE, log, parseArgs, readEnvFile, ROOT } from "./lib/env.ts";

const USAGE = "usage: node scripts/demo-manifest.ts [--env deployments/<engine>.env]";
const OUT_DIR = join(ROOT, "apps", "web", "src", "content", "demo");

function readJournal(path: string): Journal {
  if (!existsSync(path)) throw new Error(`${relative(ROOT, path)} does not exist: run scripts/seed.ts and scripts/e2e-live.ts for this engine first`);
  return JSON.parse(readFileSync(path, "utf8")) as Journal;
}

/** `engine-s3.rose-app.testnet` → `engineS3RoseAppTestnet`. */
function identifier(engine: string): string {
  const words = engine.split(/[^A-Za-z0-9]+/).filter((word) => word.length > 0);
  return words.map((word, index) => (index === 0 ? word.toLowerCase() : `${word.charAt(0).toUpperCase()}${word.slice(1).toLowerCase()}`)).join("");
}

function registrySource(engines: readonly string[]): string {
  const imports = engines.map((engine) => `import ${identifier(engine)} from "./${engine}.json";`);
  const entries = engines.map((engine) => `  "${engine}": ${identifier(engine)},`);
  return [
    "/**",
    " * Every engine with a guided demo manifest. Generated by `scripts/demo-manifest.ts` from the",
    " * JSON files next to this one; run the script again instead of editing this file.",
    " */",
    "",
    ...imports,
    "",
    "export const DEMO_MANIFESTS: Readonly<Record<string, unknown>> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

function main(): void {
  const args = parseArgs(process.argv.slice(2), USAGE);
  if (args.step !== "all") throw new Error(`unexpected argument ${args.step}\n${USAGE}`);
  const envFile = args.flags.get("env") ?? DEFAULT_ENV_FILE;
  const engine = readEnvFile(join(ROOT, envFile)).get("NEXT_PUBLIC_ENGINE_ACCOUNT");
  if (!engine) throw new Error(`${envFile} has no NEXT_PUBLIC_ENGINE_ACCOUNT`);
  const paths = ["deployments/e2e/cindral.json", `deployments/e2e/${engine}.seed.json`, `deployments/e2e/${engine}.live.json`] as const;
  const solanaPath = `deployments/e2e/${engine}.solana.json`;
  const solana = existsSync(join(ROOT, solanaPath)) ? (JSON.parse(readFileSync(join(ROOT, solanaPath), "utf8")) as SolanaJournal) : undefined;
  const manifest = buildDemoManifest({
    cast: readJournal(join(ROOT, paths[0])),
    seed: readJournal(join(ROOT, paths[1])),
    live: readJournal(join(ROOT, paths[2])),
    ...(solana ? { solana } : {}),
    paths: solana ? [...paths, solanaPath] : [...paths],
  });
  const out = join(OUT_DIR, `${engine}.json`);
  writeFileSync(out, `${JSON.stringify(manifest, null, 2)}\n`);
  const engines = readdirSync(OUT_DIR)
    .filter((file) => file.endsWith(".json"))
    .map((file) => file.slice(0, -".json".length))
    .sort();
  writeFileSync(join(OUT_DIR, "index.ts"), registrySource(engines));
  const steps = manifest.scenarios.reduce((sum, scenario) => sum + scenario.steps.length, 0);
  const txs = manifest.scenarios.reduce((sum, scenario) => sum + scenario.steps.reduce((inner, step) => inner + step.txs.length, 0), 0);
  log(`${relative(ROOT, out)}: ${String(manifest.scenarios.length)} rounds (${manifest.scenarios.map((scenario) => `#${scenario.roundId} ${scenario.key}`).join(", ")}), ${String(steps)} steps, ${String(txs)} transactions`);
  log(`${relative(ROOT, join(OUT_DIR, "index.ts"))}: ${engines.join(", ")}`);
}

main();
